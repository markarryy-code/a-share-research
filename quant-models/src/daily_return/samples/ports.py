"""样本用例需要的I/O能力；具体路径、数组句柄不进入应用。"""

from typing import Protocol, Iterable
from .domain import PreparationDescription, StockHistory, PreparationChunk, StoredSamples, ReadReceipt, PreparationSummary, PreparedIndex


class PreparedMatrices(Protocol):
    """按明确行号返回数组副本；文件映射生命周期由实现持有。"""
    index: PreparedIndex
    def features_at(self, indices): ...
    def targets_at(self, indices): ...
    def close(self) -> None: ...


class PreparedReader(Protocol):
    def read_index(self, reference: str) -> PreparedIndex: ...
    def open_matrices(self, index: PreparedIndex) -> PreparedMatrices: ...
    def verify_unchanged(self) -> ReadReceipt: ...


class HistorySource(Protocol):
    def describe(self) -> PreparationDescription: ...
    def read_markets(self): ...
    def iter_stocks(self) -> Iterable[StockHistory]: ...
    def verify_current(self) -> None: ...
    def verify_unchanged(self) -> ReadReceipt: ...


class PreparedWriter(Protocol):
    def append(self, chunk: PreparationChunk) -> None: ...
    def publish(self, summary: PreparationSummary, receipt: ReadReceipt) -> StoredSamples: ...
    def close(self) -> None: ...


class PreparedStore(Protocol):
    def initialize(self, feature_manifest: dict) -> None: ...
    def find_complete(self, identity: dict) -> StoredSamples | None: ...
    def begin(self, identity: dict, description: PreparationDescription, feature_manifest: dict) -> PreparedWriter: ...
    def finish(self, result: dict, receipt: ReadReceipt, issues: list[dict], stored: StoredSamples | None) -> None: ...
