"""时间方案用例消费的窄接口。"""

from typing import Protocol
from .domain import SamplePopulation, SplitPlan, FoldSelection


class SampleSource(Protocol):
    def read_population(self) -> SamplePopulation: ...
    def verify_unchanged(self): ...


class SplitWriter(Protocol):
    def append(self, selection: FoldSelection) -> None: ...
    def publish(self, receipt) -> dict: ...


class SplitStore(Protocol):
    def identity(self, population: SamplePopulation, plan: SplitPlan) -> dict: ...
    def find_complete(self, identity) -> dict | None: ...
    def begin(self, population: SamplePopulation, plan: SplitPlan, identity) -> SplitWriter: ...
    def finish(self, result, receipt, issues) -> None: ...
