"""跨方法共用的原始样本读取、留出使用登记与资源观测契约。"""

from typing import Protocol, Iterable
from .evaluation_domain import FoldDescription, PredictionBatch


class PredictionSource(Protocol):
    def describe(self) -> FoldDescription: ...
    def training_data(self): ...
    def prediction_batches(self, size: int) -> Iterable[PredictionBatch]: ...
    def prediction_targets(self): ...
    def verify_unchanged(self): ...
    def close(self) -> None: ...


class FoldSource(PredictionSource, Protocol):
    def validation_data(self): ...


class HoldoutSource(PredictionSource, Protocol):
    def enable_holdout_scoring(self) -> None: ...


class HoldoutUsage(Protocol):
    def reserve(self, description: FoldDescription, configuration) -> None: ...
    def mark_exposed(self) -> None: ...
    def finish(self, state: str) -> None: ...


class RunTelemetry(Protocol):
    def checkpoint(self, phase: str): ...
    def records(self): ...
