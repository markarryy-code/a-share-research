"""收益回归训练与归档接口。"""

from typing import Protocol
from .evaluation_domain import FoldDescription
from .validation_domain import ValidationSettings


class FittedModel(Protocol):
    summary: dict
    def predict(self, features): ...
    def export_text(self) -> str: ...
    def feature_usage(self): ...


class ModelTrainer(Protocol):
    def fit(self, train_x, train_y, valid_x, valid_y, names, settings: ValidationSettings) -> FittedModel: ...
    def check_reload(self, text: str, names, features, expected): ...


class ValidationArchive(Protocol):
    def begin(self, description: FoldDescription, configuration) -> None: ...
    def fitted(self, model: FittedModel, boundaries) -> None: ...
    def predictions(self, rows, values) -> None: ...
    def predictions_finished(self) -> None: ...
    def evaluated(self, truth, prediction, metrics) -> None: ...
    def finish(self, result, receipt, issues, resources) -> None: ...
